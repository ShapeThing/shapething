import { useInterfaceLanguage } from "@/outputs/render/hooks/useInterfaceLanguage.tsx";
import { bestByLanguage } from "@/helpers/bestByLanguage.ts";
import { localName } from "@/helpers/localName.ts";
import { localNameLabel } from "@/helpers/localNameLabel.ts";
import { rdf, rdfs, sh } from "@/helpers/namespaces.ts";
import { prefixedIri } from "@/helpers/prefixedIri.tsx";
import { getRdfList } from "@/helpers/rdfList.ts";
